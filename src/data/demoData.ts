/**
 * Twelve months of net-worth history ending this month. The final point
 * matches the net worth computed from the demo accounts (assets minus
 * liabilities) so the dashboard's month-over-month change reads correctly.
 */
const currentDemoNetWorth = demoAccounts
  .filter((account) => account.includeInNetWorth)
  .reduce((sum, account) => {
    const isLiability = ["credit_card", "auto_loan", "mortgage"].includes(
      account.accountType,
    );
    return sum + (isLiability ? -account.currentBalance : account.currentBalance);
  }, 0);

export const demoNetWorthHistory = Array.from({ length: 12 }, (_, i) => {
  const date = new Date();
  date.setMonth(date.getMonth() - (11 - i));
  const base = currentDemoNetWorth - (11 - i) * 1400;
  const wobble = i === 11 ? 0 : Math.sin(i * 1.7) * 900;
  return {
    month: date.toISOString().slice(0, 7),
    netWorth: Math.round(base + wobble),
  };
});
